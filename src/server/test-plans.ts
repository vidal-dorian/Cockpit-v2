// Shared by the acceptance tests of slice 13.2 (decision 077). Pinned where the decision leaves room (the developer follows these):
//
// The plan is computed at every read (077 A), from the JS clock: every date the server writes or compares comes from `new Date()` (never SQL `now()` or a
// column default), because the tests move time with fake timers (only `Date`). Table `pro_codes` (the rest of its columns is the developer's choice);
// the code is kept hashed (015): neither the code nor the note is in any history entry, and the code is in no column in clear.
//
// GET  /api/me/plan (session; 401 without)
//        -> 200 { plan: "free" | "pro", via: "admin" | "code" | null, until: ISO | null, repos: number, limit: 3 | null }
//        `repos` = the projects the account OWNS, archived included (B); `limit` is null for Pro; `until` is the end of a code (null = no end, and for an admin).
// POST /api/me/pro-code  { code }  (session)  -> 200 (same body as GET /api/me/plan) | 400 { error: "invalid_code" } (one answer for unknown, used, expired,
//        revoked, malformed or empty); history `enter_pro_code` ok or refused, args { codeId } when the code exists, never the text typed. A code is
//        bound to the account (used by one person only); a new code replaces the previous one of a Pro account.
// GET  /api/settings/pro-codes (administrator; 403 for others, 401 without)
//        -> 200 { codes: [{ id, note, state: "free" | "used" | "expired" | "revoked", until: ISO | null, createdAt: ISO, expiresAt: ISO, login: string | null }] } newest first,
//        `until` being the end of the Pro the code gives once used (null = no end), `expiresAt` the date a never-entered code stops being enterable
//        (createdAt + 30 days), `login` the linked account when used. Never the secret.
// POST /api/settings/pro-codes { note: string (1..80 after trim), until: ISO | null (a future instant) }
//        -> 201 { code: <as listed>, secret: string }  (the secret is shown this once); 400 { error: "Bad request" } (note empty or over 80, until in the past or not a date)
//        history `create_pro_code` ok, args { codeId }.
// PATCH /api/settings/pro-codes/:id { until: ISO | null } (a USED code only: 409 { error: "not_used" } otherwise; 404 unknown; 400 past date) -> 200 { code }; history `change_pro_code`.
// POST /api/settings/pro-codes/:id/revoke (a free or used code; 409 { error: "already_revoked" } on a revoked one; 404 unknown) -> 200 { code }; history `revoke_pro_code`.
// GET  /api/projects: each project also says `lockedBy` (the owner's login when the project is read-only for the plan of its owner, null otherwise; E),
//        `ownerPlan` ("free" | "pro", the plan of its owner, D) and, when locked, `role` is "read_only" for every member, the owner included.
// Quota (B, C): POST /api/projects and POST /api/projects/from-template -> 403 { error: "plan" } for a Free owner of 3 projects, journaled `refused` (detail { reason: "plan" }).
// Read-only (E): a gesture refused for the plan is 403 { error: "plan" } on a route and "Refused: ... plan ..." on an MCP tool, journaled `refused` with detail
//        { reason: "plan" } on the project (the same entry as the role's refusal, with another reason); reads stay open.
// MCP (D): submit_code_map, submit_findings and create_takeover_stories answer "Refused: ... plan ..." when the OWNER of the project is Free, before reading GitHub.

export const FREE_LIMIT = 3;
const DAY = 86_400_000;

export const get = (app: App, cookie: string, path: string) =>
  app.request(path, { headers: { cookie } });

/** An administrator (login admin99, always Pro) with a session. */
export const admin = (db: TestDb) => createAdminWithSession(db, 99);

/** The administrator generates a code; returns its id and secret (the response must be a 201). */
export async function generate(
  app: App,
  adminCookie: string,
  body: { note?: string; until?: string | null } = {},
) {
  const res = await send(app, adminCookie, "POST", "/api/settings/pro-codes", {
    note: "pour Karim",
    until: null,
    ...body,
  });
  const json = (await res.json()) as {
    code: { id: number };
    secret: string;
  };
  return { res, id: json.code?.id, secret: json.secret };
}

export const enter = (app: App, cookie: string, code: string) =>
  send(app, cookie, "POST", "/api/me/pro-code", { code });

/** The account gets Pro by a code generated by the administrator; returns the code's id. */
export async function makePro(
  app: App,
  adminCookie: string,
  cookie: string,
  until: string | null = null,
) {
  const made = await generate(app, adminCookie, { until });
  const res = await enter(app, cookie, made.secret);
  if (res.status !== 200)
    throw new Error(`entering the code must work, got ${res.status}`);
  return made.id as number;
}

export const revoke = (app: App, adminCookie: string, id: number) =>
  send(app, adminCookie, "POST", `/api/settings/pro-codes/${id}/revoke`);

export const planOf = async (app: App, cookie: string) =>
  (await get(app, cookie, "/api/me/plan")).json() as Promise<{
    plan: string;
    via: string | null;
    until: string | null;
    repos: number;
    limit: number | null;
  }>;

/** `n` more projects owned by the user, imported one day apart from 2026-01-01 on (so older than anything created now), repo ids from 100. */
export async function ownMore(db: TestDb, ownerId: number, n: number) {
  const ids: number[] = [];
  for (let i = 0; i < n; i++) {
    const [project] = await db
      .insert(projects)
      .values({
        githubRepoId: 100 + ids.length + ownerId * 1000,
        fullName: `owner${ownerId}/old${i}`,
        defaultBranch: "main",
        installationId: 77,
        createdAt: new Date(Date.UTC(2026, 0, 1 + i)),
      })
      .returning({ id: projects.id });
    if (!project) throw new Error("project insert returned no row");
    await db
      .insert(projectMembers)
      .values({ projectId: project.id, userId: ownerId, role: "owner" });
    ids.push(project.id);
  }
  return ids;
}

/** Moves the clock forward (only `Date`); the sessions are made to outlive it. Reset with `vi.useRealTimers()` in afterEach. */
export async function travel(db: TestDb, days: number) {
  await db.execute(sql`update sessions set expires_at = '2100-01-01'`);
  if (!vi.isFakeTimers()) vi.useFakeTimers({ toFake: ["Date"] });
  vi.setSystemTime(Date.now() + days * DAY);
}

export const inDays = (days: number) =>
  new Date(Date.now() + days * DAY).toISOString();
